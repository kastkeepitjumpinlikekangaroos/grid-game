  private val overrides = new java.util.HashMap[Int, String]()

  private def set(sound: String, ids: Byte*): Unit =
    ids.foreach(id => byType(id & 0xFF) = sound)

  private def only(sound: String, character: CharacterId, id: Byte): Unit =
    overrides.put(key(character.id, id), sound)

  private def key(characterId: Byte, projectileType: Byte): Int =
    ((characterId & 0xFF) << 8) | (projectileType & 0xFF)

